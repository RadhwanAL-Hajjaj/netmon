BR = [(n, re.compile(p, re.I)) for n, p in BRANDS]
picked = {}
for a, b, c, sh, lo in rows:
    for n, rx in BR:
        if rx.search(lo):
            picked[int(a + b + c, 16)] = n
            break
names = sorted(set(picked.values()))
assert len(names) < 256
idx = {n: i for i, n in enumerate(names)}
keys = sorted(picked)
